// Fetches the real Wiktionary entries shown in the screenshots (via the extension's own parser)
// and writes store/src/defs.js. Run: node store/fetch-defs.mjs
import fs from "fs";
import path from "path";
import { wiktionaryLookup } from "../src/background/wiktionary.js";

const here = path.dirname(new URL(import.meta.url).pathname);
const WORDS = [["fuimos", "es"], ["compramos", "es"], ["queso", "es"], ["temprano", "es"], ["市場", "ja"], ["일찍", "ko"], ["tôt", "fr"]];
const out = {};
for (const [w, l] of WORDS) {
  await new Promise((r) => setTimeout(r, 2500)); // be gentle with the Wikimedia API (429 otherwise)
  out[w] = await wiktionaryLookup(w, l, { userAgent: "DualCoach/0.1.0 (Chrome extension; store screenshots)" });
  console.log(w, "→", out[w] ? (out[w].lemma || out[w].headword) : "not found");
}
fs.writeFileSync(path.join(here, "src/defs.js"), "// Generated by store/fetch-defs.mjs from en.wiktionary.org (CC BY-SA 4.0).\nwindow.DEFS = " + JSON.stringify(out, null, 1) + ";\n");
